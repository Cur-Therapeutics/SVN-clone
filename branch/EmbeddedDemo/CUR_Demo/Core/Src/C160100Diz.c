#define C160100DiZ_ADDR (0x3F << 1)
// Reset pin: PD5
#define NHD_RST_PORT GPIOD
#define NHD_RST_PIN  GPIO_PIN_5

#define NHD_CS_PORT        GPIOB
#define NHD_CS_PIN         GPIO_PIN_9

#define LCD_W 160
#define LCD_H 100
#define LCD_PAGES (LCD_H / 8)

uint8_t fb[LCD_W * LCD_PAGES];

// Set pixel in framebuffer
void set_pixel(int x, int y, int color)
{
    if (x < 0 || x >= LCD_W || y < 0 || y >= LCD_H) return;

    int page = y / 8;
    int bit  = y % 8;

    if (color)
        fb[page * LCD_W + x] |= (1 << bit);
    else
        fb[page * LCD_W + x] &= ~(1 << bit);
}

void draw_big_4(int x0, int y0)
{
    for (int y = 0; y < 40; y++)
    {
        for (int x = 0; x < 20; x++)
        {
            if ((x < 5 && y > 15) || (y > 15 && y < 20) || (x > 15))
                set_pixel(x0 + x, y0 + y, 1);
        }
    }
}

void draw_big_2(int x0, int y0)
{
    for (int y = 0; y < 40; y++)
    {
        for (int x = 0; x < 20; x++)
        {
            if ((y < 5) ||
                (y > 35) ||
                (y > 15 && y < 20) ||
                (x > 15 && y < 20) ||
                (x < 5 && y > 20))
            {
                set_pixel(x0 + x, y0 + y, 1);
            }
        }
    }
}

const uint8_t font5x7[][5] = {
    // m
    {0x00,0x1C,0x04,0x18,0x04},
    // H
    {0x1F,0x04,0x04,0x04,0x1F},
    // g
    {0x18,0x24,0x24,0x3C,0x04},
};

void draw_char(int x, int y, const uint8_t *ch)
{
    for (int col = 0; col < 5; col++)
    {
        uint8_t line = ch[col];
        for (int row = 0; row < 7; row++)
        {
            if (line & (1 << row))
                set_pixel(x + col, y + row, 1);
        }
    }
}

void draw_mmHg(int x, int y)
{
    draw_char(x + 0,  y, font5x7[0]);  // m
    draw_char(x + 6,  y, font5x7[0]);  // m
    draw_char(x + 12, y, font5x7[1]);  // H
    draw_char(x + 18, y, font5x7[2]);  // g
}

void generate_image(void)
{
    memset(fb, 0x00, sizeof(fb));

    // Center "42"
    draw_big_4(40, 20);
    draw_big_2(70, 20);

    // "mmHg" underneath
    draw_mmHg(55, 70);
}

