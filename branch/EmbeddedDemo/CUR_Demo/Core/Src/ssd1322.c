/**
 * ssd1322_test.c
 *
 * Test driver for NHD-2.8-25664 OLED display (SSD1322 controller)
 * Target: STM32 (HAL-based) via SPI
 *
 * Display specs:
 *   - Resolution: 256 x 64 pixels
 *   - Interface: 4-wire SPI
 *   - Grayscale: 16 levels (4-bit per pixel)
 *   - Each column address covers 4 pixels (2 bytes = 2 nibbles each)
 *
 * Wiring assumptions (adjust pin definitions below to match your board):
 *   STM32 SPI MOSI  -> Display SDIN
 *   STM32 SPI SCK   -> Display SCLK
 *   STM32 GPIO (CS) -> Display /CS  (active low)
 *   STM32 GPIO (DC) -> Display D/C# (low=command, high=data)
 *   STM32 GPIO (RST)-> Display /RES (active low)
 */

